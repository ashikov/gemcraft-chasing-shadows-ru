def phrase_values(phrase, number, high='21', mode='NORMAL'):
    values = {'n': number, 'hi': high}
    if phrase.raw_number:
        factor = (1 if mode == 'NORMAL' else 4) if phrase.start == 14210 else (10 if mode == 'NORMAL' else 2)
        values['bonus'] = str(int(number) * factor)
    return values


def catalog_literals():
    return {row['id']: row['manual']['translation']
            for row in load_catalog('translations/catalog.json')['entries']}


def joined(phrase, literals, number, high='21', singular=False, mode='NORMAL'):
    parts = phrase.parts
    if singular and phrase.method == 784 and phrase.start in (483, 528):
        parts = (parts[0], parts[1] + 8)
    return ''.join(literals[f'abc.4175.{phrase.method}.{part}'] if isinstance(part, int)
                   else part.format(**phrase_values(phrase, number, high, mode)) for part in parts)
